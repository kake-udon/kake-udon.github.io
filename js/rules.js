function renderSection(section, index) {
  const items = section.items.map((item) => `
    <div class="rule-item">
      <div class="rule-term">${item.term}</div>
      <div class="rule-text">${item.text}</div>
    </div>
  `).join('');

  return `
    <details class="collapsible rule-section" ${index === 0 ? 'open' : ''}>
      <summary>
        <span class="section-title" style="margin:0;">${section.title}</span>
        <svg class="chevron" width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><path d="m9 18 6-6-6-6"/></svg>
      </summary>
      <div class="rule-item-list">${items}</div>
    </details>
  `;
}

export async function renderRules(container) {
  container.innerHTML = RULE_SECTIONS.map((section, i) => renderSection(section, i)).join('');
}
