// 直前に表示した豆知識と異なるものをランダムに選ぶ。
// options.preferCategory を渡すと、そのカテゴリから3回に2回の割合で引く
// （ポストシーズン中でも他のカテゴリの豆知識が出なくならないようにするため）。
export function pickTrivia(excludeText, options = {}) {
  const preferred = options.preferCategory
    ? TRIVIA.filter((t) => t.category === options.preferCategory)
    : [];
  const pool = preferred.length && Math.random() < 2 / 3 ? preferred : TRIVIA;
  const candidates = pool.filter((t) => t.text !== excludeText);
  const list = candidates.length ? candidates : pool;
  return list[Math.floor(Math.random() * list.length)];
}
